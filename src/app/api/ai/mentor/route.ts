import { NextRequest, NextResponse } from 'next/server';
import { aiMentorRequestSchema } from '@/lib/validations';

// In-memory rate limiting map: userId/ip -> timestamps[]
const rateLimitMap = new Map<string, number[]>();
const MAX_REQUESTS_PER_HOUR = 25;
const WINDOW_MS = 60 * 60 * 1000;

function checkRateLimit(key: string): boolean {
  const now = Date.now();
  const timestamps = rateLimitMap.get(key) || [];
  const validTimestamps = timestamps.filter(t => now - t < WINDOW_MS);
  
  if (validTimestamps.length >= MAX_REQUESTS_PER_HOUR) {
    return false;
  }
  validTimestamps.push(now);
  rateLimitMap.set(key, validTimestamps);
  return true;
}

export async function POST(req: NextRequest) {
  try {
    const ip = req.headers.get('x-forwarded-for') || 'local_user';
    if (!checkRateLimit(ip)) {
      return NextResponse.json(
        { 
          error: 'Rate limit reached', 
          message: 'You have reached the maximum of 25 AI Mentor queries per hour. Please take a moment to test your current setup or review the troubleshooting notes!' 
        },
        { status: 429 }
      );
    }

    const body = await req.json();
    const parseResult = aiMentorRequestSchema.safeParse(body);
    if (!parseResult.success) {
      return NextResponse.json(
        { error: 'Invalid request data', details: parseResult.error.flatten() },
        { status: 400 }
      );
    }

    const { projectTitle, currentStep, code, language, userQuestion } = parseResult.data;
    const apiKey = process.env.GEMINI_API_KEY;

    // If Gemini API Key is configured, attempt real Gemini API call
    if (apiKey && apiKey !== 'your-gemini-api-key') {
      try {
        const systemPrompt = `You are KITE STEM Mentor, an encouraging, friendly, and practical robotics and coding guide for Indian school students (Classes 3 to 12).
Project: "${projectTitle || 'STEM Project'}" (Step: ${currentStep || 1})
Language: ${language || 'General'}
Student's Current Code:
\`\`\`${language || ''}
${code || '// No code provided'}
\`\`\`

Pedagogical Rules:
1. Speak in warm, clear, age-appropriate language.
2. Never give the complete copy-paste solution directly; ask guiding questions and point out where the bug or logical flaw is.
3. If the student has hardware or wiring questions (e.g. ultrasonic sensors, motors, servos, relays), explain the physics simply (e.g. speed of sound, common ground, pull-down resistors).
4. Emphasize physical safety (e.g. disconnecting power before wiring, not shorting batteries).
5. Keep answers concise (under 200 words) with bullet points.`;

        const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 10000);

        const geminiRes = await fetch(geminiUrl, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          signal: controller.signal,
          body: JSON.stringify({
            contents: [
              {
                role: 'user',
                parts: [{ text: `${systemPrompt}\n\nStudent's Question:\n${userQuestion}` }]
              }
            ],
            generationConfig: {
              maxOutputTokens: 600,
              temperature: 0.6
            }
          })
        });

        clearTimeout(timeoutId);

        if (geminiRes.ok) {
          const geminiData = await geminiRes.json();
          const responseText = geminiData.candidates?.[0]?.content?.parts?.[0]?.text;
          if (responseText) {
            return NextResponse.json({
              provider: 'gemini',
              reply: responseText,
              disclaimer: 'Generated by KITE AI Mentor (Gemini). Always verify physical wiring before powering up.'
            });
          }
        }
      } catch (err) {
        console.warn('Gemini API call failed or timed out, falling back to local STEM mentor engine:', err);
      }
    }

    // High quality contextual fallback STEM mentor response
    const fallbackResponse = generateSTEMFallback(projectTitle, currentStep, userQuestion, code, language);
    return NextResponse.json({
      provider: 'kite_local_mentor_engine',
      reply: fallbackResponse,
      disclaimer: 'Provided by KITE STEM Knowledge Engine (Offline Mode). Test your circuit safely!'
    });

  } catch (error) {
    console.error('AI Mentor Error:', error);
    return NextResponse.json(
      { error: 'An unexpected error occurred while communicating with the AI Mentor.' },
      { status: 500 }
    );
  }
}

function generateSTEMFallback(
  projectTitle?: string,
  currentStep?: number,
  question: string = '',
  code: string = '',
  language: string = ''
): string {
  const q = question.toLowerCase();

  if (q.includes('not moving') || q.includes('motor') || q.includes('wheels')) {
    return `### 🤖 Motor & Movement Troubleshooting:
1. **Check Common Ground:** Ensure the battery ground (-) is connected to BOTH the motor driver GND and the Arduino GND. Without a shared ground, control signals cannot complete the circuit!
2. **Power Supply:** Motors draw significant current. Never power yellow BO motors or DC motors directly from the Arduino 5V pin. Use an external 2-cell Li-ion (7.4V) or 9V battery pack connected to the driver's 12V terminal.
3. **PWM Speed Pins:** Verify the enable jumpers (ENA/ENB) on your L298N driver. If using software speed control, make sure \`analogWrite(ENA, 180)\` is set to a value above 140 (below this, motor friction may prevent spinning).`;
  }

  if (q.includes('sensor') || q.includes('ultrasonic') || q.includes('distance') || q.includes('0 cm')) {
    return `### 📡 Ultrasonic Sensor Guide (HC-SR04):
1. **Pin Mapping:** Verify Trig is configured as \`OUTPUT\` and Echo is configured as \`INPUT\`.
2. **Echo Timing:** Distance is calculated using:
   \`distance_cm = (duration_microseconds * 0.034) / 2\`
3. **Sound Obstructions:** Ensure no dangling jumper wires are hanging directly in front of the sensor cylinders.
4. **Soft Obstacles:** Curtains and soft fabrics absorb ultrasonic sound pulses instead of reflecting them. Test against a hard, flat surface like a cardboard box or book!`;
  }

  if (q.includes('syntax') || q.includes('error') || q.includes('bug') || q.includes('colon')) {
    if (language === 'python' || code.includes('def ') || code.includes('import ')) {
      return `### 🐍 Python Debugging Checklist:
1. **Indentation:** Python uses 2 or 4 spaces to group code blocks. Make sure your \`def\` and \`if\` bodies are consistently indented.
2. **Missing Colons:** Check that every \`if\`, \`elif\`, \`else\`, \`for\`, and \`def\` ends with a colon (\`:\`).
3. **Variable Names:** Python is case-sensitive! Check whether variable names match exact uppercase/lowercase characters.`;
    } else {
      return `### ⚙️ Arduino C++ Debugging Checklist:
1. **Semicolons:** Did you forget a semicolon (\`;\`) at the end of a line or variable declaration?
2. **Braces:** Count your curly braces \`{\` and \`}\`. Each opened brace must have a corresponding closing brace.
3. **Void Setup & Loop:** Ensure both \`void setup() {}\` and \`void loop() {}\` exist in your sketch.`;
    }
  }

  if (q.includes('servo') || q.includes('jitter') || q.includes('vibrat')) {
    return `### 🎯 Servo Motor Alignment:
1. **Deadband Tolerance:** When using light or distance sensors to guide servos, sensor values fluctuate naturally. Add a deadband tolerance (e.g. 15-30 units) so small fluctuations don't cause jitter.
2. **Mechanical Zero:** Detach the servo horn, command \`servo.write(90)\` in code to center it, then press-fit the horn at 90 degrees.
3. **Separate Power:** Micro servos can pull up to 500mA when stalled. Power them from a dedicated 5V supply if you notice the board resetting.`;
  }

  // General step guidance
  return `### 💡 Mentor Guidance for Step ${currentStep || 1} of "${projectTitle || 'Your Project'}":
Here are the key points to check right now:
• Review your wiring connections carefully against the schematic diagram.
• Check that input sensors have pull-down or pull-up resistors where required.
• When editing code, start with small changes and use "Verify & Simulate" to check for syntax issues before writing complex loops.
• What specific behavior or output are you seeing versus what you expected? Let me know and we will debug it together!`;
}
